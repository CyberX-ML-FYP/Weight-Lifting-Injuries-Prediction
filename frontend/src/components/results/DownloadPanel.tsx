import { FaDownload, FaFileAlt } from "react-icons/fa";
import type { AnalysisResult } from "../../types/api";
import { downloadPredictionJson, downloadExplainabilityCsv } from "../../utils/download";

interface DownloadPanelProps {
  result: AnalysisResult;
}

/**
 * Report Download panel.
 *  - Prediction JSON & Explainability CSV: generated client-side from the
 *    REAL /predict response already held in memory for this exact upload.
 *  - Feature Importance CSV / Generated Report: the live /predict endpoint
 *    does not run the offline Captum module, so these are served as
 *    clearly-labelled SAMPLE artifacts pre-generated by
 *    src/explainability/explain_prediction.py, bundled as static files
 *    under frontend/public/sample-explainability/.
 */
export default function DownloadPanel({ result }: DownloadPanelProps) {
  return (
    <div className="download-panel">
      <h4>Report Download</h4>
      <div className="download-list">
        <DownloadRow
          title="Prediction JSON"
          description="The full, live prediction report for this upload, exactly as returned by POST /predict."
          action={
            <button className="btn btn-sm btn-outline-light" onClick={() => downloadPredictionJson(result)}>
              <FaDownload className="me-1" /> .json
            </button>
          }
        />
        <DownloadRow
          title="Explainability CSV"
          description="Rule A-D scores and confidences for this upload, exported as CSV from the real response."
          action={
            <button className="btn btn-sm btn-outline-light" onClick={() => downloadExplainabilityCsv(result)}>
              <FaDownload className="me-1" /> .csv
            </button>
          }
        />
        <DownloadRow
          title="Feature Importance CSV"
          sample
          description="Captum Integrated Gradients feature-importance table from a previously-generated sample run (not recomputed for this upload)."
          action={
            <a className="btn btn-sm btn-outline-light" href="/sample-explainability/feature_importance.csv" download>
              <FaDownload className="me-1" /> .csv
            </a>
          }
        />
        <DownloadRow
          title="Generated Report"
          sample
          description="Full model_explainability.md write-up (method, mapping methodology, limitations) from the same sample run."
          action={
            <a
              className="btn btn-sm btn-outline-light"
              href="/sample-explainability/model_explainability.md"
              target="_blank"
              rel="noreferrer"
            >
              <FaFileAlt className="me-1" /> .md
            </a>
          }
        />
      </div>
    </div>
  );
}

function DownloadRow({
  title,
  description,
  action,
  sample,
}: {
  title: string;
  description: string;
  action: React.ReactNode;
  sample?: boolean;
}) {
  return (
    <div className="download-row">
      <div className="download-row-text">
        <div className="d-flex align-items-center gap-2">
          <strong>{title}</strong>
          {sample && <span className="badge-sample">Sample</span>}
        </div>
        <p className="text-muted-2 small mb-0">{description}</p>
      </div>
      {action}
    </div>
  );
}
